#!/usr/bin/env python3
"""Pack external SDK binaries and CI filesystems using the SDK Rockchip tools."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import tempfile

PROJECT = Path(__file__).resolve().parents[1]
GENERATED = {'boot.img', 'rootfs.img', 'userdata.img'}


def sha(path):
    with path.open('rb') as f:
        return hashlib.file_digest(f, 'sha256').hexdigest()


def regular(root, name):
    if not re.fullmatch(r'[A-Za-z0-9_.-]+', name) or name in ('.', '..'):
        raise ValueError(f'unsafe firmware filename: {name}')
    path = root / name
    if path.is_symlink() or not path.is_file() or not path.stat().st_size:
        raise ValueError(f'missing regular firmware input: {name}')
    return path


def entries(root):
    result = {}
    for line in regular(root, 'package-file').read_text().splitlines():
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        fields = line.split()
        if len(fields) != 2 or fields[0] in result:
            raise ValueError('invalid or duplicate package-file entry')
        name, filename = fields
        if not re.fullmatch(r'[A-Za-z0-9_.-]+', name):
            raise ValueError('invalid partition name')
        if filename != 'RESERVED':
            # Validate names even for generated images, which are not staged yet.
            if not re.fullmatch(r'[A-Za-z0-9_.-]+', filename) or filename in ('.', '..'):
                raise ValueError('unsafe package-file path')
        result[name] = filename
    required = {'package-file': 'package-file', 'parameter': 'parameter.txt',
                'bootloader': 'MiniLoaderAll.bin', 'uboot': 'uboot.img', 'boot': 'boot.img',
                'rootfs': 'rootfs.img', 'userdata': 'userdata.img'}
    if any(result.get(k) != v for k, v in required.items()):
        raise ValueError('package-file must include loader, parameter, boot, rootfs and userdata')
    return result


def check(root):
    root = root.resolve()
    package = entries(root)
    expected = set(package.values()) - GENERATED - {'RESERVED'}
    expected |= {'afptool', 'rkImageMaker'}
    manifest = json.loads(regular(root, 'manifest.json').read_text())
    if manifest.get('schema') != 'ubuntu-sdk-firmware-v1' or set(manifest.get('sha256', {})) != expected:
        raise ValueError('firmware manifest does not cover exactly the SDK inputs')
    for name, digest in manifest['sha256'].items():
        if not re.fullmatch('[a-f0-9]{64}', digest) or sha(regular(root, name)) != digest:
            raise ValueError(f'firmware checksum mismatch: {name}')
    # This is exactly how the SDK updateimg hook determines the chip tag.
    tag = regular(root, 'MiniLoaderAll.bin').read_bytes()[21:25][::-1].decode('ascii')
    if not re.fullmatch('[A-Za-z0-9]{4}', tag):
        raise ValueError('invalid SDK loader chip tag')
    return root, package, tag


def stage(sdk, inputs):
    firmware = sdk.resolve() / 'output/firmware'
    with tempfile.TemporaryDirectory(dir=inputs.parent) as tmp:
        dest = Path(tmp)
        # Use the package list generated by the SDK's completed updateimg build.
        package = sdk.resolve() / 'output/update/Image/package-file'
        shutil.copyfile(package, dest / 'package-file')
        package = entries(dest)
        for name in set(package.values()) - GENERATED - {'RESERVED', 'package-file'}:
            shutil.copyfile(firmware / name, dest / name)
        for name in ('afptool', 'rkImageMaker'):
            shutil.copyfile(sdk / 'tools/linux/Linux_Pack_Firmware/rockdev' / name, dest / name)
        manifest = {'schema': 'ubuntu-sdk-firmware-v1',
                    'sha256': {p.name: sha(p) for p in sorted(dest.iterdir())}}
        (dest / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
        check(dest)
        if inputs.exists():
            raise ValueError('firmware input directory already exists; preserve or remove it explicitly')
        shutil.copytree(dest, inputs)
    print(f'Staged external SDK firmware inputs: {inputs}')


def verified_image(images, pattern):
    matches = list(images.glob(pattern))
    if len(matches) != 1:
        raise ValueError(f'expected one filesystem image: {pattern}')
    path = regular(images, matches[0].name)
    checksum = regular(images, path.name + '.sha256').read_text().split()
    if len(checksum) != 2 or checksum[1] != path.name or checksum[0] != sha(path):
        raise ValueError(f'filesystem checksum mismatch: {path.name}')
    return path


def pack(inputs, images, output):
    root, package, tag = check(inputs)
    if platform.machine() not in ('x86_64', 'amd64'):
        raise ValueError('SDK pack tools require an x86_64 runner; rootfs builds remain native ARM64')
    if output.exists() or output.with_suffix(output.suffix + '.zst').exists():
        raise ValueError('firmware output exists; use a fresh output path')
    selected = {'boot.img': verified_image(images, 'boot-*.img'),
                'rootfs.img': verified_image(images, 'ubuntu-rootfs.img'),
                'userdata.img': verified_image(images, 'userdata-*.img')}
    capacities = {}
    text = regular(root, 'parameter.txt').read_text()
    for size, offset, name in re.findall(r'(0x[0-9a-fA-F]+|-)@(0x[0-9a-fA-F]+)\(([^)]+)\)', text):
        part = name.split(':')[0]
        if part in capacities:
            raise ValueError('duplicate partition in parameter.txt')
        capacities[part] = None if size == '-' else int(size, 16) * 512
    if not capacities:
        raise ValueError('cannot parse SDK partition table')
    for part, name in package.items():
        if part in ('package-file', 'parameter', 'bootloader') or name == 'RESERVED':
            continue
        if part not in capacities:
            raise ValueError(f'package partition missing from parameter: {part}')
        source = selected[name] if name in GENERATED else regular(root, name)
        if capacities[part] is not None and source.stat().st_size > capacities[part]:
            raise ValueError(f'image exceeds partition capacity: {part}')
    for tool, path in [('fsck.erofs', selected['rootfs.img']), ('e2fsck', selected['boot.img']), ('e2fsck', selected['userdata.img'])]:
        subprocess.run([tool, *(['-fn'] if tool == 'e2fsck' else []), str(path)], check=True)
    if (images / 'packages.manifest').exists():
        verified_image(images, 'packages.manifest')
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=output.parent) as tmp:
        work = Path(tmp)
        for name in set(package.values()) - {'RESERVED'}:
            source = selected[name] if name in GENERATED else regular(root, name)
            (work / name).symlink_to(source.resolve())
        for name in ('afptool', 'rkImageMaker'):
            shutil.copyfile(root / name, work / name)
            (work / name).chmod(0o755)
        subprocess.run([str(work / 'afptool'), '-pack', './', 'update.raw.img'], cwd=work, check=True)
        subprocess.run([str(work / 'rkImageMaker'), '-RK' + tag, 'MiniLoaderAll.bin',
                        'update.raw.img', 'update.img', '-os_type:androidos'], cwd=work, check=True)
        packed = work / 'update.img'
        with packed.open('rb') as stream:
            if stream.read(4) != b'RKFW':
                raise ValueError('SDK packer did not produce an RKFW image')
        packed.rename(output)
    receipt = {'schema': 'ubuntu-flashable-image-v1', 'hardware_acceptance': 'not_performed_by_ci',
               'source_commit': os.environ.get('GITHUB_SHA'),
               'build_inputs_sha256': os.environ.get('BUILD_INPUTS_SHA256'),
               'sdk_inputs': json.loads((root / 'manifest.json').read_text()),
               'filesystems': {name: sha(path) for name, path in selected.items()},
               'update_img_sha256': sha(output),
               'packages_manifest_sha256': sha(images / 'packages.manifest') if (images / 'packages.manifest').exists() else None}
    (output.parent / (output.name + '.json')).write_text(json.dumps(receipt, indent=2) + '\n')
    subprocess.run(['zstd', '-q', '-T0', '-10', str(output), '-o', str(output) + '.zst'], check=True)
    compressed = Path(str(output) + '.zst')
    (output.parent / (compressed.name + '.sha256')).write_text(f'{sha(compressed)}  {compressed.name}\n')
    if (images / 'packages.manifest').exists():
        manifest = verified_image(images, 'packages.manifest')
        target = output.parent / (output.name + '.manifest')
        shutil.copyfile(manifest, target)
        Path(str(target) + '.sha256').write_text(f'{sha(target)}  {target.name}\n')
    print(f'Flashable SDK image: {compressed}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=('stage', 'check', 'pack'))
    parser.add_argument('--inputs', type=Path, default=PROJECT / 'artifacts/firmware')
    parser.add_argument('--sdk', type=Path, default=PROJECT.parent)
    parser.add_argument('--images', type=Path)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    if args.mode == 'stage':
        args.inputs.parent.mkdir(parents=True, exist_ok=True)
        stage(args.sdk, args.inputs)
    elif args.mode == 'check':
        check(args.inputs)
        print('SDK firmware inputs verified')
    else:
        if args.images is None or args.output is None:
            parser.error('pack requires --images and --output')
        pack(args.inputs, args.images.resolve(), args.output.resolve())


if __name__ == '__main__':
    main()
